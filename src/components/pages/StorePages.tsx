export const StoreInformationPage: React.FC<{ path: string }> = ({ path }) => {
  const { siteConfig } = useStore();
  const content = pageContent[path];
  const config = siteConfig.store;
  const values = {
    ncrDays: config.ncrDeliveryDays,
    panIndiaDays: config.panIndiaDeliveryDays,
    phone: config.whatsappNumber,
    address: config.atelierAddress,
    city: config.city,
    state: config.state,
    pincode: config.pincode,
  };
  const whatsappUrl = `https://wa.me/91${config.whatsappNumber}?text=${encodeURIComponent('Namaste Charmzy! I have a question about your store policies.')}`;

  if (!content) {
    return (
      <PageFrame title="Page not found" intro="We couldn’t find that page. Browse the latest collections or return to the storefront.">
        <div className="flex flex-wrap gap-3">
          <a href="/shop" className="rounded-xl bg-pink-600 px-5 py-3 text-sm font-bold text-white">Shop collections</a>
          <a href="/" className="rounded-xl border border-pink-200 bg-white px-5 py-3 text-sm font-bold text-zinc-800">Home</a>
        </div>
      </PageFrame>
    );
  }

  return (
    <PageFrame title={content.title} intro={content.intro}>
      {content.sections.map(section => (
        <section key={section.title} className="rounded-2xl border border-pink-200 bg-white/90 p-5 shadow-sm backdrop-blur sm:p-7">
          <h2 className="font-outfit text-lg font-bold text-zinc-900">{section.title}</h2>
          <div className="mt-3 space-y-3 text-sm leading-6 text-zinc-600">
            {section.body.map((paragraph, index) => (
              <p key={index}>{interpolate(paragraph, values)}</p>
            ))}
          </div>
        </section>
      ))}
      <a href={whatsappUrl} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-2 rounded-xl bg-emerald-600 px-5 py-3 text-sm font-bold text-white hover:bg-emerald-700">
        <MessageCircle className="h-4 w-4" /> Ask us on WhatsApp
      </a>
    </PageFrame>
  );
};

export const ProductPage: React.FC<{ product: Product }> = ({ product }) => {
  const { addToCart, siteConfig } = useStore();
  const [finish, setFinish] = useState<string>(product.defaultFinish);
  const [added, setAdded] = useState(false);

  useEffect(() => {
    document.title = `${product.title} | CHARMZY JEWELLERY`;
  }, [product.title]);

  const stockAvailable = product.inStock && product.stockCount > 0;

  return (
    <PageFrame title={product.title} intro={product.description}>
      <div className="grid gap-6 rounded-3xl border border-pink-200 bg-white/95 p-4 shadow-sm backdrop-blur md:grid-cols-2 md:p-7">
        <div className="space-y-3">
          <div className="aspect-square overflow-hidden rounded-2xl bg-pink-50">
            <img src={product.images[0]} alt={product.title} className="h-full w-full object-cover" />
          </div>
          <div className="grid grid-cols-3 gap-2">
            {product.images.slice(1, 4).map(image => <img key={image} src={image} alt="" className="aspect-square w-full rounded-xl object-cover" />)}
          </div>
        </div>
        <div className="flex flex-col gap-4">
          <p className="text-xs font-bold uppercase tracking-wider text-pink-600">{product.category.replaceAll('-', ' ')}</p>
          <div className="flex items-center gap-3">
            <span className="font-outfit text-3xl font-black text-pink-700">{formatINR(product.price)}</span>
            {product.mrp > product.price && <span className="text-sm text-zinc-400 line-through">{formatINR(product.mrp)}</span>}
          </div>
          <p className={`text-sm font-semibold ${stockAvailable ? 'text-emerald-700' : 'text-rose-700'}`}>{stockAvailable ? 'Available to inquire' : 'Currently unavailable'}</p>
          <p className="text-sm leading-6 text-zinc-600">{product.description}</p>
          <label className="space-y-2 text-sm font-semibold text-zinc-800">
            Finish
            <select value={finish} onChange={event => setFinish(event.target.value)} className="block w-full rounded-xl border border-pink-200 bg-white px-3 py-2.5">
              {[product.defaultFinish, 'rose-pink', 'silver-tone', 'golden-tone', 'oxidised'].filter((value, index, list) => list.indexOf(value) === index).map(value => (
                <option key={value} value={value}>{value.replaceAll('-', ' ')}</option>
              ))}
            </select>
          </label>
          <div className="rounded-xl bg-pink-50 p-4 text-sm text-zinc-700">
            <p className="font-bold text-zinc-900">Product details</p>
            <dl className="mt-2 space-y-1">
              {Object.entries(product.specifications).map(([label, value]) => <div key={label} className="flex justify-between gap-3"><dt className="capitalize text-zinc-500">{label}</dt><dd className="text-right">{value}</dd></div>)}
            </dl>
          </div>
          {(siteConfig.offers.b2g1Active || siteConfig.offers.b6g4Active) && (
            <div className="rounded-xl border border-pink-200 bg-white p-4 text-sm">
              <p className="font-bold text-pink-700">Current offers</p>
              {siteConfig.offers.b2g1Active && <p className="mt-1">{siteConfig.offers.b2g1Label}</p>}
              {siteConfig.offers.b6g4Active && <p className="mt-1">{siteConfig.offers.b6g4Label}</p>}
              <p className="mt-2 text-xs text-zinc-500">Eligible offers are calculated in your bag and confirmed by our team.</p>
            </div>
          )}
          <button type="button" disabled={!stockAvailable} onClick={() => { if (addToCart(product, finish)) { setAdded(true); window.setTimeout(() => setAdded(false), 1800); } }} className="inline-flex items-center justify-center gap-2 rounded-xl bg-pink-600 px-5 py-3 font-bold text-white disabled:cursor-not-allowed disabled:opacity-50">
            {added ? <Check className="h-4 w-4" /> : <ShoppingBag className="h-4 w-4" />}{added ? 'Added to bag' : 'Add to bag'}
          </button>
          <a href="/shipping" className="inline-flex items-center gap-2 text-sm font-semibold text-pink-700"><Truck className="h-4 w-4" /> Shipping and delivery details</a>
        </div>
      </div>
    </PageFrame>
  );
};

export const CartPage: React.FC = () => {
  const { cart, updateQuantity, removeFromCart, clearCart, offerBreakdown, subtotal, itemsTotal, setIsCheckoutOpen } = useStore();
  return (
    <PageFrame title="Your shopping bag" intro="Review your selections and applicable offers. Your order is only confirmed after our team replies to your WhatsApp inquiry.">
      {cart.length === 0 ? (
        <section className="rounded-2xl border border-pink-200 bg-white/90 p-8 text-center">
          <ShoppingBag className="mx-auto h-10 w-10 text-pink-500" />
          <p className="mt-3 font-bold text-zinc-900">Your bag is empty</p>
          <a href="/shop" className="mt-4 inline-flex items-center gap-2 rounded-xl bg-pink-600 px-5 py-3 font-bold text-white">Explore collections <ArrowRight className="h-4 w-4" /></a>
        </section>
      ) : (
        <>
          <div className="space-y-3">
            {cart.map(item => (
              <article key={`${item.productId}-${item.selectedFinish}`} className="flex gap-4 rounded-2xl border border-pink-200 bg-white/95 p-4 shadow-sm">
                <a href={`/products/${item.product.slug}`} className="h-24 w-24 shrink-0 overflow-hidden rounded-xl bg-pink-50"><img src={item.product.images[0]} alt={item.product.title} className="h-full w-full object-cover" /></a>
                <div className="min-w-0 flex-1">
                  <a href={`/products/${item.product.slug}`} className="font-bold text-zinc-900 hover:text-pink-700">{item.product.title}</a>
                  <p className="mt-1 text-xs capitalize text-zinc-500">Finish: {item.selectedFinish.replaceAll('-', ' ')}</p>
                  <p className="mt-2 font-bold text-pink-700">{formatINR(item.product.price)} each</p>
                  <div className="mt-2 flex items-center gap-3">
                    <button aria-label="Decrease quantity" onClick={() => updateQuantity(item.productId, item.selectedFinish, -1)} className="rounded border px-2">−</button>
                    <span>{item.quantity}</span>
                    <button aria-label="Increase quantity" onClick={() => updateQuantity(item.productId, item.selectedFinish, 1)} className="rounded border px-2">+</button>
                    <button onClick={() => removeFromCart(item.productId, item.selectedFinish)} className="ml-auto text-xs font-semibold text-rose-600">Remove</button>
                  </div>
                </div>
              </article>
            ))}
          </div>
          <section className="rounded-2xl border border-pink-200 bg-white/95 p-5 shadow-sm">
            <h2 className="font-outfit text-lg font-bold text-zinc-900">Order summary</h2>
            {offerBreakdown.totalOfferSavings > 0 && <p className="mt-3 text-sm text-emerald-700">Offer savings: −{formatINR(offerBreakdown.totalOfferSavings)}</p>}
            <p className="mt-2 text-sm text-zinc-600">Subtotal: {formatINR(subtotal)}</p>
            <p className="mt-2 text-sm text-zinc-600">Courier shipping: calculated after delivery area and courier partner are confirmed.</p>
            <p className="mt-3 border-t border-pink-100 pt-3 text-lg font-black text-zinc-900">Items total (shipping excluded): {formatINR(itemsTotal)}</p>
            <p className="mt-2 text-xs leading-5 text-zinc-500">Final availability, offer, delivery-partner shipping charge, order total and payment details are confirmed in WhatsApp. No payment is collected on this website.</p>
            <div className="mt-4 flex flex-wrap gap-3">
              <button onClick={() => setIsCheckoutOpen(true)} className="rounded-xl bg-pink-600 px-5 py-3 text-sm font-bold text-white">Continue to WhatsApp inquiry</button>
              <button onClick={clearCart} className="rounded-xl border border-pink-200 px-5 py-3 text-sm font-semibold text-zinc-700">Clear bag</button>
              <a href="/shipping" className="inline-flex items-center gap-2 rounded-xl border border-pink-200 px-4 py-3 text-sm font-semibold text-pink-700"><Truck className="h-4 w-4" /> Shipping info</a>
            </div>
          </section>
        </>
      )}
    </PageFrame>
  );
};
